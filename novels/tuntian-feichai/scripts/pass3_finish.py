def stats(text):
    lines = text.strip().split("\n")
    body = "\n".join(l for l in lines if not l.startswith("#"))
    non_ws = re.sub(r"\s+", "", body)
    ze = non_ws.count("则")
    n = len(non_ws)
    return n, ze, ze / (n / 1000) if n else 0

def sc(t):
    return sum(t.count(s) for s in SLOGANS)

