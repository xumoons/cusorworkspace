def stats(text):
    lines = text.strip().split("\n")
    body = "\n".join(l for l in lines if not l.startswith("#"))
    non_ws = re.sub(r"\s+", "", body)
    ze = non_ws.count("则")
    n = len(non_ws)
    dens = ze / (n / 1000) if n else 0
    return n, ze, dens

def slogan_count(text):
    return sum(text.count(s) for s in SLOGANS)

def main():
    all_ok = True
    for fname, expansion in EXPANSIONS.items():
        path = BASE / fname
        content = path.read_text(encoding="utf-8").rstrip() + expansion
        path.write_text(content, encoding="utf-8")
        n, ze, dens = stats(content)
        sc = slogan_count(content)
        ok = n >= 2500 and dens < 12 and sc <= 2
        if not ok:
            all_ok = False
        print(f"{fname}: chars={n} ze={ze} dens={dens:.2f}/1k slogan_total={sc} [{'PASS' if ok else 'FAIL'}]")
    return 0 if all_ok else 1

if __name__ == "__main__":
    raise SystemExit(main())
