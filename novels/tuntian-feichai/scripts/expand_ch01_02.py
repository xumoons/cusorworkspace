"""Expand chapters to >=2500 non-whitespace chars. Gate enforced."""
from pathlib import Path

OUT = Path("/workspace/novels/tuntian-feichai/chapters")
MIN_CHARS = 2500


def count(text: str) -> int:
    return len("".join(ch for ch in text if not ch.isspace()))


def save(name: str, text: str) -> None:
    n = count(text)
    if n < MIN_CHARS:
        raise SystemExit(f"FAIL {name}: {n} < {MIN_CHARS}")
    OUT.joinpath(name).write_text(text.strip() + "\n", encoding="utf-8")
    print(f"OK {name}: {n}")


